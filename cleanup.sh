#!/usr/bin/env bash
# cleanup.sh — one-shot teardown of the old Spark React app + Chrome extension.
#
# Run this ONCE after pulling the new code. It removes only the broken
# Spark project files. The new TypeScript skills CLI (src/api, src/lib,
# src/skills, src/cli.ts, tests/, .github/workflows/redeem.yml,
# .github/workflows/test.yml) is left intact, as is your Squad / Spec Kit /
# Copilot tooling under .github/.
#
# Usage:
#   bash cleanup.sh           # delete files via plain rm
#   bash cleanup.sh --git     # delete via `git rm -rf` so the deletions are staged

set -euo pipefail

GIT_MODE=0
if [[ "${1:-}" == "--git" ]]; then
  GIT_MODE=1
fi

remove() {
  local path="$1"
  if [[ ! -e "$path" && ! -L "$path" ]]; then
    return 0
  fi
  if [[ $GIT_MODE -eq 1 ]]; then
    git rm -rf --quiet --ignore-unmatch -- "$path"
  else
    rm -rf -- "$path"
  fi
  echo "removed: $path"
}

# Old React/Spark app source — the new code lives in src/api, src/lib,
# src/skills and src/cli.ts which are NOT in this list.
remove src/App.tsx
remove src/ErrorFallback.tsx
remove src/main.tsx
remove src/index.css
remove src/main.css
remove src/vite-end.d.ts
remove src/components
remove src/hooks
remove src/styles
remove src/lib/utils.ts
remove src/lib/types.ts
remove src/lib/gifts-data.ts

# Old Chrome extension and its build helpers
remove extension
remove scripts

# Spark/Vite/Tailwind tooling and obsolete docs
remove index.html
remove vite.config.ts
remove vite.config.extension.ts
remove tailwind.config.js
remove components.json
remove theme.json
remove runtime.config.json
remove spark.meta.json
remove .spark-initial-sha
remove EXTENSION_SUMMARY.md
remove INSTALLATION.md
remove PRD.md
remove QUICKSTART.md
remove SECURITY.md

# Old node_modules and lockfile (the new package.json has totally different deps)
remove node_modules
# package-lock.json is regenerated by `npm install` against the new package.json,
# but the old one references React/Radix/Spark deps and will confuse `npm ci`.
remove package-lock.json

echo
echo "Cleanup complete."
echo
echo "Next steps:"
echo "  1) npm install             # install the new dependencies"
echo "  2) npm test                # run the test suite"
echo "  3) npm run typecheck       # verify types"
echo "  4) See docs/SETUP.md to capture your STFC store JWT and configure"
echo "     the STFC_ACCOUNTS GitHub Actions secret."
